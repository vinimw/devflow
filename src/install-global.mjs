import {
  existsSync, lstatSync, realpathSync, readFileSync, mkdirSync,
  symlinkSync, writeFileSync, chmodSync, statSync,
} from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILL_SOURCE = join(projectRoot, 'skills', 'devflow');
const CLI_SOURCE = join(projectRoot, 'bin', 'devflow.mjs');
const IDENTIFIER = '# DevFlow global CLI PATH';

function quoteForShell(value) {
  return "'" + value.replaceAll("'", "'\\''") + "'";
}
function presence(path) {
  try { return lstatSync(path); }
  catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}
function ensureRegularSource() {
  for (const path of [join(SKILL_SOURCE, 'SKILL.md'), CLI_SOURCE]) {
    if (!presence(path)?.isFile()) {
      throw new Error('Arquivo necessário do DevFlow não encontrado: ' + path);
    }
  }
}
function linkPlan(path, source) {
  const current = presence(path);
  if (!current) return { path, action: 'create', kind: 'link' };
  if (!current.isSymbolicLink()) {
    return { path, action: 'conflict', kind: 'link', reason: 'Arquivo ou diretório existente deve ser preservado' };
  }
  try {
    if (realpathSync(path) === realpathSync(source)) {
      return { path, action: 'unchanged', kind: 'link' };
    }
  } catch {
    // Broken links and inaccessible targets are never overwritten.
  }
  return { path, action: 'conflict', kind: 'link', reason: 'Link simbólico existente aponta para outro destino ou está quebrado' };
}
function filePlan(path, desired) {
  const current = presence(path);
  if (!current) return { path, action: 'create', kind: 'script' };
  if (!current.isFile()) {
    return { path, action: 'conflict', kind: 'script', reason: 'O caminho existente não é um arquivo comum' };
  }
  if (readFileSync(path, 'utf8') !== desired) {
    return { path, action: 'conflict', kind: 'script', reason: 'O executável existente possui conteúdo diferente' };
  }
  return { path, action: 'unchanged', kind: 'script' };
}
function profilePlan(path, line) {
  const current = presence(path);
  if (!current) return { path, action: 'create', kind: 'profile' };
  if (!current.isFile()) {
    return { path, action: 'conflict', kind: 'profile', reason: 'O perfil do terminal não é um arquivo comum' };
  }
  const content = readFileSync(path, 'utf8');
  if (content.includes(line)) return { path, action: 'unchanged', kind: 'profile' };
  return { path, action: 'append', kind: 'profile' };
}
function shellConfig(shell) {
  const name = shell?.split('/').at(-1);
  if (name === 'zsh') return '.zshrc';
  if (name === 'bash') return '.bashrc';
  return null;
}
function conflictMessage(plans) {
  const conflicts = plans.filter(item => item.action === 'conflict');
  return 'Instalação global bloqueada; revise os caminhos existentes antes de tentar novamente:\n' +
    conflicts.map(item => '- ' + item.path + ': ' + item.reason).join('\n');
}

/**
 * Install the same reusable skill for both agents, and a small, executable
 * local shell wrapper for the CLI without modifying the Git checkout.
 *
 * The installer never overwrites an existing incompatible installation and
 * does not call GitHub, any AI provider, or any network endpoint.
 */
export function globalInstall({
  home = homedir(), shell = process.env.SHELL, pathEnv = process.env.PATH ?? '',
  apply = false, skipShell = false,
} = {}, output = console.log) {
  ensureRegularSource();
  const root = resolve(home);
  if (!presence(root)?.isDirectory()) throw new Error('Diretório pessoal não encontrado: ' + root);
  if (!statSync(projectRoot).isDirectory()) throw new Error('Repositório local do DevFlow não encontrado');

  const linkTargets = [
    join(root, '.claude', 'skills', 'devflow'),
    join(root, '.agents', 'skills', 'devflow'),
  ];
  const binDir = join(root, '.local', 'bin');
  const executable = join(binDir, 'devflow');
  // Use a wrapper rather than a link: cloning the repository does not
  // guarantee the executable mode of bin/devflow.mjs.
  const runner = '#!/bin/sh\n' +
    '# Generated by the DevFlow global installer; edit the source checkout instead.\n' +
    'exec node ' + quoteForShell(CLI_SOURCE) + ' "$@"\n';

  const plans = linkTargets.map(path => linkPlan(path, SKILL_SOURCE));
  plans.push(filePlan(executable, runner));

  const profileName = shellConfig(shell);
  const alreadyOnPath = pathEnv.split(':').includes(binDir);
  const profileLine = 'export PATH="$HOME/.local/bin:$PATH"';
  const profile = !skipShell && profileName && !alreadyOnPath
    ? join(root, profileName)
    : null;
  if (profile) plans.push(profilePlan(profile, profileLine));

  const result = {
    source: projectRoot,
    mode: apply ? 'apply' : 'preview',
    files: plans.map(({path,action,kind,reason}) => ({path,action,kind,...(reason ? {reason} : {})})),
    shell: shell ?? null,
    pathConfigured: alreadyOnPath || Boolean(profile),
    requiresShellRestart: Boolean(profile),
    noAIRequests: true,
    noGitHubWrites: true,
  };

  if (plans.some(item => item.action === 'conflict')) {
    result.ok = false;
    result.message = conflictMessage(plans);
    output?.(result);
    if (apply) throw new Error(result.message);
    return result;
  }
  if (apply) {
    for (const entry of plans) {
      if (entry.action === 'unchanged') continue;
      // Re-check to avoid accidentally overwriting paths created in between.
      const path = entry.path;
      if (entry.kind === 'link') {
        if (presence(path)) throw new Error('O caminho foi alterado após a verificação inicial: ' + path);
        mkdirSync(dirname(path), {recursive:true});
        symlinkSync(SKILL_SOURCE, path, 'dir');
      } else if (entry.kind === 'script') {
        if (presence(path)) throw new Error('Path changed after preflight: ' + path);
        mkdirSync(dirname(path), {recursive:true});
        writeFileSync(path, runner, {flag:'wx',mode:0o755});
        chmodSync(path, 0o755);
      } else if (entry.kind === 'profile') {
        const line = IDENTIFIER + '\n' + profileLine + '\n';
        if (entry.action === 'create') {
          if (presence(path)) throw new Error('O perfil do terminal foi alterado após a verificação inicial: ' + path);
          writeFileSync(path, line, {flag:'wx'});
        } else if (entry.action === 'append') {
          if (!presence(path)?.isFile()) throw new Error('Profile changed after preflight: ' + path);
          const content = readFileSync(path,'utf8');
          if (!content.includes(profileLine)) {
            const newline = content.endsWith('\n') || content === '' ? '' : '\n';
            writeFileSync(path, newline + '\n' + line, {flag:'a'});
          }
        }
      }
    }
  }
  result.ok = true;
  result.message = apply
    ? 'DevFlow instalado globalmente. Reinicie o terminal ou a sessão do agente, se necessário, para atualizar o PATH e o reconhecimento da skill.'
    : 'Apenas prévia. Revise as alterações e execute novamente com --apply para aplicar.';
  output?.(result);
  return result;
}

export function parseInstallArgs(argv) {
  const [scope,...args] = argv;
  if (scope !== 'global') throw new Error('Usage: devflow install global [--apply] [--home DIR] [--skip-shell]');
  const opts = {};
  for (let i=0;i<args.length;i++) {
    const arg = args[i];
    if (arg === '--apply') {opts.apply = true; continue;}
    if (arg === '--skip-shell') {opts.skipShell = true; continue;}
    if (arg === '--home') {
      const home = args[++i];
      if (!home || home.startsWith('--')) throw new Error('Informe o diretório após --home');
      opts.home = home; continue;
    }
    throw new Error('Opção de instalação desconhecida: ' + arg);
  }
  return opts;
}

export function installMain(argv, output=console.log) {
  return globalInstall(parseInstallArgs(argv), output);
}
